import { svg, box, poly, valley, arrow, intersect, reflect, WHITE_SIDE } from '../../diagrams/kit.js'

const COLOR = '#4d9de0'
const FLAP = '#2f7cc0'

// Треугольник: сгиб внизу, открытый уголок сверху
const A = [40, 200]
const B = [260, 200]
const C = [150, 90]

// Левый уголок кладём на правую сторону так, чтобы верхний край клапана стал горизонтальным
const s = (B[0] - A[0]) / (2 + Math.SQRT2)
const F = [A[0] + s, A[1] - s]
const A2 = [B[0] - s, B[1] - s]
const E = intersect(F, [(A[0] + A2[0]) / 2, (A[1] + A2[1]) / 2], A, B)
const E2 = [300 - E[0], E[1]]
const B2 = F
const topTip = reflect(C, F, A2)

const Z = '25 30 250 250'

const leftFlap = poly([F, E, A2], FLAP)
const rightFlap = poly([A2, E2, B2], FLAP)

const finished = box(Z, poly([E, E2, A2, F], COLOR), leftFlap, rightFlap, poly([F, A2, topTip], WHITE_SIDE))

